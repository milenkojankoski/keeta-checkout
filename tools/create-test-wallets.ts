/**
 * Create the two development wallets (merchant and payer) for the Keeta test network
 * and write their seeds to `.env.test`.
 *
 * Run: pnpm wallets:create          (refuses to overwrite an existing .env.test)
 *      pnpm wallets:create --force  (replaces it, orphaning any funds on the old wallets)
 *
 * Seeds are written to the gitignored `.env.test` and are never printed. The addresses
 * are printed, because those are public and you need them for the faucet and explorer.
 */
import { existsSync, writeFileSync, chmodSync } from 'node:fs';
import { Account, ENV_FILE, SEED_VAR, WALLET_ROLES, explorerAccountUrl, loadTestEnv } from './keeta.ts';

const force = process.argv.includes('--force');

loadTestEnv();

if (existsSync(ENV_FILE) && !force) {
  console.error(`${ENV_FILE} already exists.`);
  console.error('Run `pnpm wallets:status` to see the existing wallets,');
  console.error('or `pnpm wallets:create --force` to replace them (any test funds on the old wallets are lost).');
  process.exit(1);
}

const seeds = new Map<string, string>();
const lines: string[] = [
  '# Development wallets for the Keeta test network.',
  `# Generated by \`pnpm wallets:create\` on ${new Date().toISOString()}.`,
  '#',
  '# Gitignored. These wallets hold only test-network value, but a seed is still a key:',
  '# never reuse one of these on the main network.',
  '',
  'KEETA_NETWORK=test',
  ''
];

for (const role of WALLET_ROLES) {
  const seed = Account.generateRandomSeed({ asString: true });
  seeds.set(role, seed);
  lines.push(`# ${role}`, `${SEED_VAR[role]}=${seed}`, '');
}

writeFileSync(ENV_FILE, lines.join('\n'), { encoding: 'utf8', mode: 0o600 });
try {
  chmodSync(ENV_FILE, 0o600);
} catch {
  // Windows ignores POSIX modes. The file is still gitignored.
}

console.log(`Wrote ${ENV_FILE} (gitignored).\n`);
for (const role of WALLET_ROLES) {
  const seed = seeds.get(role);
  if (seed === undefined) throw new Error(`no seed generated for ${role}`);
  const address = Account.fromSeed(seed, 0).publicKeyString.get();
  console.log(`${role.padEnd(9)} ${address}`);
  console.log(`${''.padEnd(9)} ${explorerAccountUrl(address)}\n`);
}

console.log('Next: `pnpm wallets:fund` asks the test faucet for KTA, then `pnpm wallets:status`.');
